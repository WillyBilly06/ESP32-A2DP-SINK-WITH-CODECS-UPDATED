"""Generate immutable interpolated polyphase Q30 FIR banks; no runtime float."""
from pathlib import Path
import math

PHASES=128
TAPS=(96,48,24)
CUTOFF=0.475
BETA=7.5
Q=1<<30

def i0(x):
    term=1.0;total=1.0;y=x*x/4.0
    for k in range(1,80):
        term*=y/(k*k);total+=term
        if term<total*1e-16:break
    return total

def bank(taps):
    delay=taps//2-1;radius=delay;denom=i0(BETA)-1.0
    rows=[]
    for phase in range(PHASES):
        frac=phase/PHASES;weights=[]
        for k in range(taps):
            x=k-delay+frac
            if abs(x)>=radius:window=0.0
            else:window=(i0(BETA*math.sqrt(max(0.0,1.0-(x/radius)**2)))-1.0)/denom
            angle=2*CUTOFF*x
            sinc=1.0 if angle==0 else math.sin(math.pi*angle)/(math.pi*angle)
            weights.append(2*CUTOFF*sinc*window)
        total=sum(weights);q=[round(x/total*Q) for x in weights]
        index=max(range(taps),key=lambda i:abs(q[i]));q[index]+=Q-sum(q)
        if any(v < -(1<<31) or v>=(1<<31) for v in q) or sum(q)!=Q:raise RuntimeError('coefficient bounds')
        rows.append(q)
    # The final row is an exact source-index shift, guaranteeing continuity
    # across a Q32 phase wrap. The first coefficient of phase zero is zero.
    if rows[0][0]!=0:raise RuntimeError('phase-zero boundary')
    rows.append(rows[0][1:]+[0])
    bound=max(sum(abs(v) for v in row) for row in rows)+taps
    if bound >= 1<<32:raise RuntimeError('Q31 x Q30 sum may overflow int64')
    return rows,bound

def main():
    target=Path(__file__).resolve().parents[1]/'src/dbt_resampler_coeffs.inc'
    lines=['/* Generated by tools/gen_resampler_coeffs.py; Q30 interpolated Kaiser sinc. */']
    for taps in TAPS:
        rows,bound=bank(taps)
        lines.append(f'#define DBT_RESAMPLER_BOUND_{taps} {bound}ull')
        lines.append(f'_Static_assert(DBT_RESAMPLER_BOUND_{taps} < (1ull<<32), "resampler accumulation bound");')
        lines.append(f'static const int32_t coefficients_{taps}[129][{taps}] = {{')
        lines.extend('    {'+','.join(map(str,row))+'},' for row in rows)
        lines.append('};')
        print(f'{taps} taps: max absolute coefficient sum including rounding = {bound}, < 2^32')
    target.write_text('\n'.join(lines)+'\n',encoding='utf-8')
    print(f'wrote {target}, {sum(TAPS)*(PHASES+1)*4} coefficient bytes in flash')
if __name__=='__main__':main()
