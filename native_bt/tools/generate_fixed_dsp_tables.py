"""Generate flash-only integer DSP coefficients; no target-side float design."""
import argparse
import math
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
RATES = [8000, 11025, 12000, 16000, 22050, 24000, 32000, 44100, 48000, 88200, 96000, 176400, 192000]
Q = 1 << 28


def coefficients(kind, rate, frequency, gain=0):
    frequency = min(frequency, rate * 0.45)
    angle = 2 * math.pi * frequency / rate
    cosine, sine = math.cos(angle), math.sin(angle)
    a = 10 ** (gain / 40)
    alpha = sine / math.sqrt(2)
    if kind in ("low", "high"):
        t = 2 * math.sqrt(a) * alpha
        if kind == "low":
            numerator = [a*((a+1)-(a-1)*cosine+t), 2*a*((a-1)-(a+1)*cosine), a*((a+1)-(a-1)*cosine-t)]
            denominator = [(a+1)+(a-1)*cosine+t, -2*((a-1)+(a+1)*cosine), (a+1)+(a-1)*cosine-t]
        else:
            numerator = [a*((a+1)+(a-1)*cosine+t), -2*a*((a-1)+(a+1)*cosine), a*((a+1)+(a-1)*cosine-t)]
            denominator = [(a+1)-(a-1)*cosine+t, 2*((a-1)-(a+1)*cosine), (a+1)-(a-1)*cosine-t]
    elif kind == "peak":
        alpha = sine / 2
        numerator = [1+alpha*a, -2*cosine, 1-alpha*a]
        denominator = [1+alpha/a, -2*cosine, 1-alpha/a]
    elif kind == "lp":
        numerator = [(1-cosine)/2, 1-cosine, (1-cosine)/2]
        denominator = [1+alpha, -2*cosine, 1-alpha]
    elif kind == "hp":
        numerator = [(1+cosine)/2, -(1+cosine), (1+cosine)/2]
        denominator = [1+alpha, -2*cosine, 1-alpha]
    else:
        raise ValueError(kind)
    values = [round(v / denominator[0] * Q) for v in numerator + denominator[1:]]
    if kind in ("low", "high", "peak") and gain == 0:
        values = [Q, 0, 0, 0, 0]
    if any(not -(1 << 31) <= v < (1 << 31) for v in values):
        raise ValueError("Coefficient exceeds signed Q4.28")
    _, _, _, a1, a2 = values
    if min(Q+a1+a2, Q-a1+a2, Q-a2) <= 0:
        raise ValueError("Quantized denominator is not strictly stable")
    return "{" + ",".join(str(v) for v in values) + "}"


def generate(low_pass, high_pass):
    lines = ["/* Generated by native_bt/tools/generate_fixed_dsp_tables.py. Flash data only. */",
             f"#define FDSP_TABLE_LP_HZ {low_pass}u", f"#define FDSP_TABLE_HP_HZ {high_pass}u",
             f"#define FDSP_RATE_COUNT {len(RATES)}u",
             "static const uint32_t fdsp_rates[] = {" + ",".join(map(str, RATES)) + "};",
             "static const int32_t fdsp_eq[][3][25][5] = {"]
    for rate in RATES:
        lines.append("{")
        for kind, frequency, scale in [("low", 150, 0.5), ("peak", 1000, 0.7), ("high", 6000, 0.7)]:
            lines.append("{" + ",\n".join(coefficients(kind, rate, frequency, gain*scale) for gain in range(-12, 13)) + "},")
        lines.append("},")
    lines += ["};", "static const int32_t fdsp_comp[][128][5] = {"]
    for rate in RATES:
        lines.append("{" + ",\n".join(coefficients("low", rate, 100, 5*(1-volume/127)**2) for volume in range(128)) + "},")
    lines += ["};", "static const int32_t fdsp_boost[][5] = {"]
    lines += [coefficients("low", rate, 150, 2) + "," for rate in RATES]
    lines += ["};", "static const int32_t fdsp_cross[][2][5] = {"]
    lines += ["{" + coefficients("lp", rate, low_pass) + "," + coefficients("hp", rate, high_pass) + "}," for rate in RATES]
    lines += ["};", "static const int32_t fdsp_analysis[][13] = {"]
    for rate in RATES:
        decimation = max(1, (rate+5512)//11025)
        effective = rate // decimation
        values = [round(2*math.cos(2*math.pi*f/effective)*(1 << 29)) for f in [30, 60, 100]]
        values += [round(math.cos(2*math.pi*f/effective)*(1 << 30)) for f in [30, 60, 100]]
        values += [round(math.sin(2*math.pi*f/effective)*(1 << 30)) for f in [30, 60, 100]]
        values += [round((2*math.pi*f/(effective+2*math.pi*f))*(1 << 31)) for f in [45, 80, 120]]
        values += [round(math.exp(-1/(effective*0.05))*(1 << 31))]
        lines.append("{" + ",".join(map(str, values)) + "},")
    lines += ["};", "static const int16_t fdsp_db_fraction_q8[256] = {"]
    lines += [",".join(str(round(20*math.log10(1+i/256)*256)) for i in range(256)), "};", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", type=Path, default=ROOT / "bt_audio_sink/sdkconfig")
    parser.add_argument("--output", type=Path, default=ROOT / "bt_audio_sink/main/dsp/fixed_dsp_tables.inc")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = args.config.read_text(encoding="utf-8")
    def setting(name):
        match = re.search(r"^CONFIG_" + name + r"=(\d+)$", text, re.M)
        if not match:
            raise ValueError("Missing " + name)
        return int(match.group(1))
    generated = generate(setting("DSP_CROSSOVER_LP_FREQ"), setting("DSP_CROSSOVER_HP_FREQ"))
    if args.check:
        if args.output.read_text(encoding="utf-8") != generated:
            raise SystemExit("Fixed DSP tables differ; regenerate for this configuration")
    else:
        args.output.write_text(generated, encoding="utf-8")
    print(f"Validated integer coefficients for {len(RATES)} sample rates")


if __name__ == "__main__":
    main()
