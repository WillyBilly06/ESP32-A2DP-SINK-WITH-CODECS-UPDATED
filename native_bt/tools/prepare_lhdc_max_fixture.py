"""Generate pinned 192k/S24/1000kbps vectors and sparse independent PCM checks.

The test encoder and unmodified sibling decoder run on the host only. Neither
is a Bluetooth-host dependency. Target execution is a separate diagnostic.
"""
import argparse
import ctypes
import hashlib
import json
import os
from pathlib import Path
import shutil
import struct
import subprocess

ROOT=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser()
parser.add_argument('--encoder',type=Path,required=True)
parser.add_argument('--decoder',type=Path,required=True,help='Sibling decoder directory containing lhdc_dec.c')
args=parser.parse_args()
enc=args.encoder.resolve();dec=args.decoder.resolve()
out=ROOT/'_build/lhdc_max_fixture';out.mkdir(parents=True,exist_ok=True)
files=sorted([*(enc/'src').glob('*.c'),*(enc/'src').glob('*.h'),*(enc/'include').glob('*.h'),*(enc/'examples').glob('*.c'),enc/'LICENSE',enc/'README.md'],key=lambda p:p.relative_to(enc).as_posix())
digest=hashlib.sha256()
for p in files:digest.update(p.relative_to(enc).as_posix().encode()+b'\0');digest.update(p.read_bytes())
assert len(files)==17 and digest.hexdigest()=='6917725b0598e56af0f7ba20490cfadeb9b0910aefa822c4b71a0af726c0651a','Encoder source pin mismatch'
env=os.environ.copy()
if os.name=='nt':
    vc=Path(r'C:\Program Files (x86)\Microsoft Visual Studio\2022\BuildTools\VC\Auxiliary\Build\vcvars64.bat')
    data=subprocess.check_output(f'call "{vc}" >nul && set',shell=True,text=True)
    env.update(dict(x.split('=',1) for x in data.splitlines() if '=' in x and not x.startswith('=')))
cc=shutil.which('clang',path=env.get('PATH')) or r'C:\Program Files\LLVM\bin\clang.exe'
cache=shutil.which('ccache',path=env.get('PATH'))
if not cache and os.name=='nt':
    matches=list((Path.home()/'.espressif/tools/ccache').glob('*/ccache-*/ccache.exe'))
    if matches:cache=str(sorted(matches)[-1])
assert cache,'ccache is required for fixture compilation'
env.pop('CCACHE_DISABLE',None)
sources=[*(enc/'src').glob('*.c'),ROOT/'tests/codecs/lhdcv5_encoder_fixture.c']
reference=[ROOT/'tests/codecs/lhdcv5_reference_probe.c']+[dec/n for n in ('lhdc_bit_reader.c','lhdc_dec.c','lhdc_diag_config.c','lhdc_entropy_dec.c','lhdc_imdct.c','lhdc_sns_synth.c','lhdc_tables.c')]
tracked=[*files,*sources,*reference,*dec.glob('*.h'),Path(__file__).resolve()]
before={str(p):hashlib.sha256(p.read_bytes()).hexdigest() for p in tracked}
def compile_units(units,includes,prefix,extra=()):
    objects=[]
    for source in units:
        obj=out/(prefix+source.stem+'.obj');objects.append(obj)
        cmd=[cache,cc,'-std=c11','-O2','-fwrapv','-D_CRT_SECURE_NO_WARNINGS',*extra]
        cmd+=['-I'+str(p) for p in includes]+['-c',str(source),'-o',str(obj)]
        subprocess.run(cmd,check=True,env=env,capture_output=True)
    return objects
objects=compile_units(sources,[enc/'include',enc/'src'],'enc_')
binary=out/('generate.exe' if os.name=='nt' else 'generate')
subprocess.run([cc,*map(str,objects),*([] if os.name=='nt' else ['-lm']),'-o',str(binary)],check=True,env=env)
packet_file=out/'192000_24_1000.packets'
subprocess.run([str(binary),'192000','24','8',str(packet_file)],check=True,env=env)
raw=packet_file.read_bytes();at=0;packets=[];total_frames=0
while at<len(raw):
    n,frames=struct.unpack_from('<HH',raw,at);at+=4
    assert 0<n<=2046 and frames==1 and at+n<=len(raw)
    packets.append(raw[at:at+n]);at+=n;total_frames+=frames
assert len(packets)==96 and total_frames==96
bitrate=sum(map(len,packets))*8*192000//(total_frames*960)
assert 1000000<=bitrate<=1010000,bitrate
ref_objects=compile_units(reference,[dec],'ref_',['-DLHDC_HOST_BUILD',*([] if os.name=='nt' else ['-fPIC'])])
library=out/('reference.dll' if os.name=='nt' else 'reference.so')
subprocess.run([cc,'-shared',*map(str,ref_objects),*([] if os.name=='nt' else ['-lm']),'-o',str(library)],check=True,env=env)
lib=ctypes.CDLL(str(library));u8=ctypes.c_uint8;u=ctypes.c_uint
lib.reference_frame.argtypes=[ctypes.POINTER(u8),u,ctypes.POINTER(u8),u,ctypes.POINTER(u),ctypes.POINTER(u)]
assert lib.reference_open(192000,24)==0
pcm=bytearray()
try:
    for packet in packets:
        src=(u8*len(packet)).from_buffer_copy(packet);dst=(u8*(960*2*4))();used=u();generated=u()
        assert lib.reference_frame(src,len(packet),dst,960,ctypes.byref(used),ctypes.byref(generated))==0
        assert used.value==len(packet) and generated.value==960
        pcm.extend(bytes(dst))
finally:lib.reference_close()
assert len(pcm)==96*960*2*4
values=struct.unpack('<'+str(len(pcm)//4)+'i',pcm)
points=[(2*(frame*960+offset)+channel,values[2*(frame*960+offset)+channel])
        for frame in (8,16,32,48,64,80,95) for offset in (0,123,501,959) for channel in (0,1)]
assert max(abs(v) for v in values)>100000000
lines=['/* Generated by prepare_lhdc_max_fixture.py; independent host oracle, not target/RF proof. */',
       '#ifndef PROBE_LHDC_MAX_FIXTURE_H','#define PROBE_LHDC_MAX_FIXTURE_H',
       'static const uint8_t lhdc_max_cie[13]={0,255,58,5,0,0,53,76,1,2,17,64,0};']
for i,packet in enumerate(packets):
    media=bytes([4,i&255])+packet
    lines.append(f'static const uint8_t lhdc_max_packet_{i}[{len(media)}]={{'+','.join(map(str,media))+'};')
lines.append('static const struct {const uint8_t *data;uint16_t size;} lhdc_max_packets[]={')
lines.extend(f'{{lhdc_max_packet_{i},sizeof(lhdc_max_packet_{i})}},' for i in range(len(packets)))
lines+=['};','static const probe_pcm_point_t lhdc_max_points[]={']
lines.extend(f'{{{index}u,{value}}},' for index,value in points)
lines+=['};','#endif','']
destination=ROOT/'esp32_probe/main/probe_lhdc_max_fixture.h'
assert all(hashlib.sha256(Path(p).read_bytes()).hexdigest()==h for p,h in before.items())
destination.write_text('\n'.join(lines),encoding='utf-8',newline='\n')
receipt={'scope':'host fixture generation and sparse reference PCM checks only; no target execution',
         'encoder_commit':'3f9d1980fa9c57cdfb78792f9455a7dbac50edda','encoder_tree_sha256':digest.hexdigest(),
         'rate':192000,'sample_depth':24,'channels':2,'quality_index':8,'encoded_payload_bps':bitrate,
         'packets':len(packets),'sample_frames':total_frames*960,'reference_points':len(points),
         'encoded_sha256':hashlib.sha256(raw).hexdigest(),'reference_pcm_sha256':hashlib.sha256(pcm).hexdigest(),
         'fixture_sha256':hashlib.sha256(destination.read_bytes()).hexdigest(),'source_sha256':before}
(out/'generation.json').write_text(json.dumps(receipt,indent=2)+'\n')
print(json.dumps({k:v for k,v in receipt.items() if k!='source_sha256'},indent=2))
